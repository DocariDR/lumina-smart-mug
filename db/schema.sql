-- Lumina : schéma de la newsletter (V3)
CREATE TABLE IF NOT EXISTS subscribers (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    status ENUM('pending', 'confirmed', 'unsubscribed') NOT NULL DEFAULT 'pending',
    confirm_token_hash CHAR(64) NULL,
    confirm_token_expires_at DATETIME NULL,
    unsubscribe_token_hash CHAR(64) NULL,
    consent_at DATETIME NOT NULL,
    consent_version VARCHAR(32) NOT NULL,
    ip_hash CHAR(64) NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    confirmed_at DATETIME NULL,
    unsubscribed_at DATETIME NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_subscribers_email (email),
    UNIQUE KEY uq_subscribers_unsubscribe_token_hash (unsubscribe_token_hash),
    KEY idx_subscribers_token_hash (confirm_token_hash)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS orders (
    id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    order_reference CHAR(16) NOT NULL,
    email VARCHAR(254) NOT NULL,
    customer_name VARCHAR(120) NOT NULL,
    shipping_address VARCHAR(255) NOT NULL,
    city VARCHAR(100) NOT NULL,
    state_code CHAR(2) NOT NULL,
    postal_code VARCHAR(10) NOT NULL,
    country_code CHAR(2) NOT NULL,
    quantity TINYINT UNSIGNED NOT NULL,
    unit_price_cents INT UNSIGNED NOT NULL,
    shipping_cents INT UNSIGNED NOT NULL DEFAULT 0,
    total_cents INT UNSIGNED NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'USD',
    total_xof INT UNSIGNED NOT NULL,
    usd_to_eur_rate_scaled INT UNSIGNED NOT NULL,
    rate_scale INT UNSIGNED NOT NULL DEFAULT 1000000,
    eur_xof_rate_scaled INT UNSIGNED NOT NULL DEFAULT 655957,
    eur_xof_scale INT UNSIGNED NOT NULL DEFAULT 1000,
    rate_at DATETIME NOT NULL,
    status ENUM('pending', 'paid', 'failed', 'cancelled', 'refunded', 'fulfilled') NOT NULL DEFAULT 'pending',
    payment_provider VARCHAR(32) NULL,
    payment_session_id VARCHAR(255) NULL,
    payment_reference VARCHAR(255) NULL,
    cgv_accepted_at DATETIME NOT NULL,
    privacy_acknowledged_at DATETIME NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    paid_at DATETIME NULL,
    cancelled_at DATETIME NULL,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uq_orders_reference (order_reference),
    UNIQUE KEY uq_orders_payment_session (payment_session_id),
    KEY idx_orders_email (email),
    KEY idx_orders_status (status),
    CONSTRAINT chk_orders_quantity CHECK (quantity BETWEEN 1 AND 99),
    CONSTRAINT chk_orders_total CHECK (total_cents = (quantity * unit_price_cents) + shipping_cents),
    CONSTRAINT chk_orders_country CHECK (country_code = 'US'),
    CONSTRAINT chk_orders_xof CHECK (total_xof > 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;